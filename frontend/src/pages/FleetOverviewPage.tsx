import { useMemo, useState } from "react";
import { Link } from "react-router-dom";
import { useBacklog, useEquipmentTypes, useHealthDistribution, useHighRisk, usePredictionTrends, useSensorTrends, useSummary } from "../api/hooks";
import type { HealthState } from "../api/types";
import { BarsChart, TimeChart, tokenColor } from "../components/charts";
import { Badge, Card, Empty, HealthBadge, Notice, PageHeader, ProbabilityBar, QueryState, Stat } from "../components/ui";
import { dateTime, label, relative, rulText } from "../lib/format";

const HEALTH_ORDER: HealthState[] = ["healthy", "watch", "at_risk", "critical", "unknown"];
const HEALTH_COLOR: Record<HealthState, string> = {
  healthy: tokenColor("ok"), watch: tokenColor("watch"), at_risk: tokenColor("warn"), critical: tokenColor("danger"), unknown: tokenColor("unknown"),
};

export default function FleetOverviewPage() {
  const summary = useSummary();
  const health = useHealthDistribution();
  const highRisk = useHighRisk();
  const trends = usePredictionTrends(14);
  const backlog = useBacklog();
  const types = useEquipmentTypes();
  const [typeKey, setTypeKey] = useState("centrifugal_pump");
  const [sensor, setSensor] = useState("vibration");
  const sensorTrends = useSensorTrends({ equipment_type: typeKey, sensor, days: 7 });
  const sensorsForType = types.data?.find((t) => t.key === typeKey)?.sensors ?? [];

  const healthRows = useMemo(() => Object.entries(health.data?.by_type ?? {}).map(([t, v]) => ({ type: t, ...v })), [health.data]);

  return (
    <div>
      <PageHeader title="Fleet overview"
        subtitle={summary.data ? `Last prediction ${relative(summary.data.last_prediction_at)} · refreshes every minute` : "Equipment health at a glance"} />

      {summary.data && summary.data.simulated_equipment > 0 && (
        <div className="mb-4"><Notice>
          <strong>{summary.data.simulated_equipment} of {summary.data.total_equipment}</strong> equipment items use <strong>simulated</strong> sensor data
          generated by the built-in simulator. Model outputs are real predictions on that synthetic data, not on physical machines.
          {summary.data.simulated_equipment < summary.data.total_equipment && " The remaining equipment holds imported data (for example the NASA C-MAPSS turbofan benchmark)."}
        </Notice></div>
      )}

      <QueryState q={summary} rows={2}>
        {(s) => (
          <div className="mb-4 grid grid-cols-2 gap-3 md:grid-cols-3 xl:grid-cols-6">
            <Stat label="Total equipment" value={s.total_equipment} hint="excluding decommissioned" />
            <Stat label="Operational" value={s.operational} hint={`${s.under_maintenance} under maintenance`} tone="ok" />
            <Stat label="Requiring attention" value={s.requiring_attention} hint="watch, at risk or critical" tone="warn" />
            <Stat label="High risk" value={s.high_risk} hint="at or above critical threshold" tone="danger" />
            <Stat label="Open work orders" value={s.open_work_orders} hint="open, assigned, in progress" />
            <Stat label="Active alerts" value={s.active_alerts} hint="open or acknowledged" tone="watch" />
          </div>
        )}
      </QueryState>

      <div className="grid gap-4 xl:grid-cols-3 xl:items-start">
        <Card title="Health distribution by type" className="xl:col-span-1">
          <QueryState q={health} empty={(d) => (Object.keys(d.by_type).length === 0 ? <Empty title="No equipment yet" /> : false)}>
            {(d) => (
              <>
                <div className="mb-3 flex flex-wrap gap-1.5">
                  {HEALTH_ORDER.map((h) => <span key={h} className="flex items-center gap-1 text-xs"><HealthBadge state={h} /><span className="tabular-nums text-subtle">{d.overall[h]}</span></span>)}
                </div>
                <BarsChart data={healthRows} xKey="type" horizontal stacked height={180}
                  bars={HEALTH_ORDER.map((h) => ({ key: h, label: label(h), color: HEALTH_COLOR[h] }))} />
              </>
            )}
          </QueryState>
        </Card>

        <Card title="Highest-risk equipment" className="xl:col-span-2" bodyClass="p-0"
          actions={<Link to="/equipment?sort=risk" className="text-xs text-primary hover:underline">View all</Link>}>
          <QueryState q={highRisk} empty={(d) => (d.length === 0 ? <Empty title="No equipment at risk">All latest predictions are low risk with no anomalies.</Empty> : false)}>
            {(rows) => (
              <div className="overflow-x-auto"><table className="w-full">
                <thead className="border-b border-border"><tr><th className="th">Equipment</th><th className="th">Health</th><th className="th">Failure risk</th><th className="th">RUL</th><th className="th">Alerts</th><th className="th">As of</th></tr></thead>
                <tbody className="divide-y divide-border">
                  {rows.map((e) => (
                    <tr key={e.id} className="hover:bg-muted/50">
                      <td className="td"><Link className="font-medium text-primary hover:underline" to={`/equipment/${e.id}`}>{e.code}</Link><div className="text-2xs text-subtle">{e.name}</div></td>
                      <td className="td"><HealthBadge state={e.health_state} /></td>
                      <td className="td"><ProbabilityBar value={e.latest_prediction?.failure_probability ?? null} level={e.latest_prediction?.risk_level} /></td>
                      <td className="td text-xs">{e.latest_prediction ? rulText(e.latest_prediction.rul_hours, e.latest_prediction.rul_status, null, e.latest_prediction.rul_unit) : "—"}</td>
                      <td className="td">{e.open_alerts ? <Badge tone="warn">{e.open_alerts}</Badge> : <span className="text-subtle">0</span>}</td>
                      <td className="td text-xs text-subtle">{relative(e.latest_prediction?.as_of)}</td>
                    </tr>
                  ))}
                </tbody>
              </table></div>
            )}
          </QueryState>
        </Card>

        <Card title="Mean predicted failure probability (daily)" className="xl:col-span-2">
          <QueryState q={trends} empty={(d) => (d.length === 0 ? <Empty title="No predictions yet" /> : false)}>
            {(d) => <TimeChart data={d.map((r) => ({ t: r.day, mean: r.mean_failure_probability }))} lines={[{ key: "mean", label: "Mean probability" }]}
              valueFormat={(v) => `${(v * 100).toFixed(0)}%`} yDomain={[0, "auto"]} height={220} />}
          </QueryState>
        </Card>

        <Card title="Recent alerts" bodyClass="p-0">
          <QueryState q={summary} empty={(s) => (s.recent_alerts.length === 0 ? <Empty title="No active alerts" /> : false)}>
            {(s) => (
              <ul className="divide-y divide-border">
                {s.recent_alerts.map((a) => (
                  <li key={a.id} className="px-4 py-2.5">
                    <div className="flex items-center justify-between gap-2">
                      <Link to={`/equipment/${a.equipment_id}`} className="text-sm font-medium text-primary hover:underline">{a.equipment_code}</Link>
                      <Badge tone={a.severity === "critical" ? "danger" : "warn"}>{a.severity === "critical" ? "Critical" : "Warning"}</Badge>
                    </div>
                    <div className="text-sm">{a.title}</div>
                    <div className="text-2xs text-subtle">{label(a.kind)} · seen {a.occurrence_count}× · last {dateTime(a.last_seen_at)}</div>
                  </li>
                ))}
              </ul>
            )}
          </QueryState>
        </Card>

        <Card title="Sensor trend across the fleet (hourly mean)" className="xl:col-span-2"
          actions={
            <div className="flex gap-2">
              <select aria-label="Equipment type" className="input !w-auto !py-1 text-xs" value={typeKey}
                onChange={(e) => { const t = types.data?.find((x) => x.key === e.target.value); setTypeKey(e.target.value); setSensor(t?.sensors[1]?.name ?? t?.sensors[0]?.name ?? ""); }}>
                {types.data?.map((t) => <option key={t.key} value={t.key}>{t.display_name}</option>)}
              </select>
              <select aria-label="Sensor" className="input !w-auto !py-1 text-xs" value={sensor} onChange={(e) => setSensor(e.target.value)}>
                {sensorsForType.map((s) => <option key={s.name} value={s.name}>{label(s.name)}</option>)}
              </select>
            </div>
          }>
          <QueryState q={sensorTrends}>
            {(d) => <TimeChart data={d.points} lines={(d.equipment ?? []).map((c) => ({ key: c, label: c }))} yLabel={d.unit}
              band={d.normal_min !== undefined && d.normal_max !== undefined ? { y1: d.normal_min, y2: d.normal_max, label: "normal band" } : undefined} />}
          </QueryState>
        </Card>

        <Card title="Maintenance backlog">
          <QueryState q={backlog}>
            {(b) => (
              <>
                <BarsChart data={(["critical", "high", "medium", "low"] as const).map((p) => ({ priority: label(p), count: b.by_priority[p] }))} xKey="priority"
                  bars={[{ key: "count", label: "Active work orders" }]} height={160} />
                <dl className="mt-3 grid grid-cols-2 gap-2 text-sm">
                  <div><dt className="text-2xs text-subtle">Overdue</dt><dd className={b.overdue ? "font-semibold text-danger" : ""}>{b.overdue}</dd></div>
                  <div><dt className="text-2xs text-subtle">Completed (30 d)</dt><dd>{b.completed_last_30_days}</dd></div>
                  <div><dt className="text-2xs text-subtle">In progress</dt><dd>{b.by_status.in_progress}</dd></div>
                  <div><dt className="text-2xs text-subtle">Mean time to complete</dt><dd>{b.mean_hours_to_complete_last_30_days ?? "—"} h</dd></div>
                </dl>
              </>
            )}
          </QueryState>
        </Card>
      </div>
    </div>
  );
}
